"""
Default NLU backend -- a reimplementation of the original Rasa NLU pipeline.

The original model (Rasa NLU 0.12.3, see ``docker/rasa-legacy``) used:

1. ``nlp_spacy`` + ``tokenizer_spacy`` -- spaCy English model and tokeniser;
2. ``ner_crf`` -- a conditional random field entity extractor (BILOU tags,
   token features in a -1/0/+1 window, L1 = 1, L2 = 0.001, 50 iterations);
3. ``ner_spacy`` -- spaCy's named entities (not used by Glass-Box);
4. ``intent_featurizer_spacy`` -- the spaCy document vector;
5. ``intent_classifier_sklearn`` -- a linear SVM with ``C`` chosen from
   ``[1, 2, 5, 10, 20, 100]`` by (up to) 5-fold cross-validation.

As in the original, ``case_sensitive: false``, so the text is lower-cased
before it is processed by spaCy;
entity values keep the original case.

This module implements steps 1, 2, 4 and 5 with spaCy 3, sklearn-crfsuite and
scikit-learn. Being retrained with newer libraries it is not bit-identical to
the 2018 model; use the ``rasa-legacy`` backend for that.
"""
import json
import logging
import os

import joblib
import numpy as np

from glassbox.nlu.base import NLUBackend
from glassbox.resources import resource_path

__all__ = ['SpacyNLU', 'DEFAULT_SPACY_MODEL', 'DEFAULT_MODEL_DIR']

logger = logging.getLogger(__name__)

DEFAULT_SPACY_MODEL = 'en_core_web_sm'
DEFAULT_MODEL_DIR = resource_path('nlu', 'model')
TRAINING_DATA = resource_path('nlu', 'training_data.json')
#: examples added in 2026 (generated by ``glassbox nlu generate``)
EXTRA_TRAINING_DATA = resource_path('nlu', 'training_data_extra.json')
C_GRID = [1, 2, 5, 10, 20, 100]
WINDOW = {-1: ['low', 'title', 'upper', 'pos', 'pos2'],
          0: ['bias', 'low', 'word3', 'word2', 'upper', 'title', 'digit',
              'pos', 'pos2'],
          1: ['low', 'title', 'upper', 'pos', 'pos2']}


def _token_feature(token, name):
    if name == 'low':
        return token.text.lower()
    if name == 'title':
        return token.text.istitle()
    if name == 'upper':
        return token.text.isupper()
    if name == 'digit':
        return token.text.isdigit()
    if name == 'word3':
        return token.text[-3:]
    if name == 'word2':
        return token.text[-2:]
    if name == 'pos':
        return token.tag_
    if name == 'pos2':
        return token.tag_[:2]
    if name == 'bias':
        return 'bias'
    raise ValueError(name)


def sentence_features(doc):
    """CRF features of every token (Rasa NLU 0.12 ``ner_crf`` layout)."""
    features = []
    for i in range(len(doc)):
        f = {}
        for offset, names in WINDOW.items():
            j = i + offset
            if 0 <= j < len(doc):
                prefix = '{}:'.format(offset) if offset else '0:'
                for name in names:
                    f[prefix + name] = _token_feature(doc[j], name)
            elif j < 0:
                f['BOS'] = True
            else:
                f['EOS'] = True
        features.append(f)
    return features


def _bilou(doc, entities):
    tags = ['O'] * len(doc)
    for en in entities:
        span = doc.char_span(en['start'], en['end'], alignment_mode='expand')
        if span is None:
            continue
        idx = list(range(span.start, span.end))
        if len(idx) == 1:
            tags[idx[0]] = 'U-' + en['entity']
        else:
            tags[idx[0]] = 'B-' + en['entity']
            for k in idx[1:-1]:
                tags[k] = 'I-' + en['entity']
            tags[idx[-1]] = 'L-' + en['entity']
    return tags


def _spans(doc, tags, text):
    """Turns BILOU tags into entities with character offsets."""
    entities, start, label = [], None, None
    for i, tag in enumerate(tags):
        prefix, _, name = tag.partition('-')
        if prefix == 'U':
            entities.append((i, i, name))
            start = None
        elif prefix == 'B':
            start, label = i, name
        elif prefix == 'I' and start is not None and name == label:
            continue
        elif prefix == 'L' and start is not None and name == label:
            entities.append((start, i, name))
            start = None
        else:
            start = None
    out = []
    for s, e, name in entities:
        span = doc[s:e + 1]
        out.append({'entity': name,
                    'value': text[span.start_char:span.end_char],
                    'start': span.start_char, 'end': span.end_char,
                    'extractor': 'ner_crf'})
    return out


def load_training_data(paths=(TRAINING_DATA, EXTRA_TRAINING_DATA)):
    """
    Rasa NLU ``common_examples`` of the given files.

    By default: the 162 original examples (the training data of the 2018
    model) and the examples added in 2026.
    """
    if isinstance(paths, str):
        paths = (paths, )
    examples = []
    for path in paths:
        with open(path) as f:
            examples += json.load(f)['rasa_nlu_data']['common_examples']
    return examples


def _load_spacy(name):
    try:
        import spacy
    except ImportError as e:  # pragma: no cover
        raise ImportError('The spacy NLU backend requires spaCy.') from e
    try:
        return spacy.load(name, disable=['ner', 'lemmatizer'])
    except OSError as e:
        raise OSError('The spaCy model {0!r} is not installed: python -m '
                      'spacy download {0}'.format(name)) from e


class SpacyNLU(NLUBackend):
    """
    spaCy + CRF + SVM natural language understanding.

    Use :meth:`train` to build a model and :meth:`load` to read a saved one.
    """

    def __init__(self, nlp, crf, classifier, labels, spacy_model):
        self.nlp = nlp
        self.crf = crf
        self.classifier = classifier
        self.labels = list(labels)
        self.spacy_model = spacy_model

    # ------------------------------------------------------------- training
    @classmethod
    def train(cls, examples=None, spacy_model=DEFAULT_SPACY_MODEL,
              random_state=42):
        """
        Trains the entity extractor and the intent classifier.

        Parameters
        ----------
        examples : list of dict, optional
            Rasa NLU ``common_examples`` (default: the Glass-Box + new data).
        spacy_model : str
            Name of the spaCy model.
        """
        import sklearn_crfsuite
        from sklearn.model_selection import GridSearchCV, StratifiedKFold
        from sklearn.svm import SVC
        examples = load_training_data() if examples is None else examples
        nlp = _load_spacy(spacy_model)
        docs = list(nlp.pipe([e['text'].lower() for e in examples]))

        crf = sklearn_crfsuite.CRF(algorithm='lbfgs', c1=1.0, c2=0.001,
                                   max_iterations=50,
                                   all_possible_transitions=True)
        crf.fit([sentence_features(d) for d in docs],
                [_bilou(d, e.get('entities', []))
                 for d, e in zip(docs, examples)])

        labels = sorted(set(e['intent'] for e in examples))
        X = np.stack([d.vector for d in docs])
        y = np.array([labels.index(e['intent']) for e in examples])
        folds = max(2, min(5, int(np.bincount(y).min())))
        search = GridSearchCV(
            SVC(kernel='linear', probability=True, class_weight='balanced',
                random_state=random_state),
            {'C': C_GRID, 'kernel': ['linear']},
            cv=StratifiedKFold(folds, shuffle=True,
                               random_state=random_state),
            scoring='f1_weighted')
        search.fit(X, y)
        return cls(nlp, crf, search.best_estimator_, labels, spacy_model)

    # ------------------------------------------------------------ persisting
    def save(self, directory=DEFAULT_MODEL_DIR):
        """Saves the model (joblib files and a metadata JSON)."""
        import sklearn
        import spacy
        os.makedirs(directory, exist_ok=True)
        joblib.dump(self.crf, os.path.join(directory, 'crf.joblib'))
        joblib.dump(self.classifier, os.path.join(directory,
                                                  'intent.joblib'))
        meta = {'spacy_model': self.spacy_model, 'labels': self.labels,
                'versions': {'spacy': spacy.__version__,
                             'scikit-learn': sklearn.__version__}}
        with open(os.path.join(directory, 'metadata.json'), 'w') as f:
            json.dump(meta, f, indent=2)
        return directory

    @classmethod
    def load(cls, model_dir=None, spacy_model=None, retrain_if_needed=True):
        """
        Loads a saved model (default: the model shipped with the package).

        If the model cannot be loaded (e.g., it was saved by an incompatible
        scikit-learn version) and ``retrain_if_needed`` is set, a new model is
        trained from the shipped training data (this takes a few seconds).
        """
        model_dir = DEFAULT_MODEL_DIR if model_dir is None else model_dir
        try:
            with open(os.path.join(model_dir, 'metadata.json')) as f:
                meta = json.load(f)
            import sklearn
            if meta['versions']['scikit-learn'] != sklearn.__version__:
                raise ValueError('The model was saved with scikit-learn {}.'
                                 .format(meta['versions']['scikit-learn']))
            if spacy_model not in (None, meta['spacy_model']):
                raise ValueError('The model uses a different spaCy model.')
            crf = joblib.load(os.path.join(model_dir, 'crf.joblib'))
            classifier = joblib.load(os.path.join(model_dir,
                                                  'intent.joblib'))
            nlp = _load_spacy(meta['spacy_model'])
            return cls(nlp, crf, classifier, meta['labels'],
                       meta['spacy_model'])
        except (OSError, ValueError, KeyError, EOFError) as e:
            if not retrain_if_needed or (isinstance(e, OSError)
                                         and 'spaCy model' in str(e)):
                raise
            logger.warning('Retraining the NLU model (%s).', e)
            return cls.train(spacy_model=spacy_model or DEFAULT_SPACY_MODEL)

    # --------------------------------------------------------------- parsing
    def parse(self, text):
        doc = self.nlp(text.lower())  # case_sensitive: false
        if len(doc):
            tags = self.crf.predict_single(sentence_features(doc))
            entities = _spans(doc, tags, text)
        else:
            entities = []
        probabilities = self.classifier.predict_proba(
            doc.vector.reshape(1, -1))[0]
        best = int(np.argmax(probabilities))
        label = self.labels[int(self.classifier.classes_[best])]
        return {'text': text,
                'intent': {'name': label,
                           'confidence': float(probabilities[best])},
                'entities': entities}
